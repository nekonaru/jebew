-- Skema final Jebew. Dijalankan lewat npm run siap:supabase.
-- Semua waktu memakai WIB. Seluruh perubahan data tercatat di log_audit.

CREATE TABLE IF NOT EXISTS pengaturan (
  kunci TEXT PRIMARY KEY,
  nilai TEXT NOT NULL
);

-- Pembatasan laju berbasis database agar tetap berlaku di banyak instance serverless.
CREATE TABLE IF NOT EXISTS pembatasan_laju (
  kunci TEXT PRIMARY KEY,
  jumlah INTEGER NOT NULL DEFAULT 0,
  reset_pada BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS pengguna (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL UNIQUE,
  nama TEXT NOT NULL,
  kata_sandi TEXT NOT NULL,
  peran TEXT NOT NULL CHECK (peran IN ('pemilik', 'kasir')),
  aktif BOOLEAN NOT NULL DEFAULT TRUE,
  sesi_versi INTEGER NOT NULL DEFAULT 0,
  dibuat_pada TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Jakarta')
);

CREATE TABLE IF NOT EXISTS log_audit (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pengguna_id INTEGER REFERENCES pengguna(id),
  aksi TEXT NOT NULL,
  tabel TEXT NOT NULL,
  catatan TEXT NOT NULL DEFAULT '',
  dibuat_pada TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Jakarta')
);

CREATE TABLE IF NOT EXISTS supplier (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama TEXT NOT NULL,
  kontak TEXT NOT NULL DEFAULT '',
  aktif BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS konversi_satuan (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dari_satuan TEXT NOT NULL,
  ke_satuan TEXT NOT NULL,
  faktor DOUBLE PRECISION NOT NULL CHECK (faktor > 0),
  UNIQUE (dari_satuan, ke_satuan)
);

CREATE TABLE IF NOT EXISTS bahan (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama TEXT NOT NULL,
  satuan TEXT NOT NULL,
  stok DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (stok >= 0),
  stok_minimum DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (stok_minimum >= 0),
  harga_rata_rata INTEGER NOT NULL DEFAULT 0 CHECK (harga_rata_rata >= 0),
  aktif BOOLEAN NOT NULL DEFAULT TRUE,
  dibuat_pada TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Jakarta')
);

CREATE TABLE IF NOT EXISTS pergerakan_stok (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bahan_id INTEGER NOT NULL REFERENCES bahan(id),
  jenis TEXT NOT NULL CHECK (jenis IN ('masuk', 'keluar', 'penyesuaian', 'rusak')),
  jumlah DOUBLE PRECISION NOT NULL,
  stok_sebelum DOUBLE PRECISION NOT NULL,
  stok_sesudah DOUBLE PRECISION NOT NULL,
  referensi TEXT NOT NULL DEFAULT '',
  catatan TEXT NOT NULL DEFAULT '',
  pengguna_id INTEGER REFERENCES pengguna(id),
  dibuat_pada TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Jakarta')
);

CREATE TABLE IF NOT EXISTS pembelian (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nomor TEXT NOT NULL UNIQUE,
  supplier_id INTEGER REFERENCES supplier(id),
  total INTEGER NOT NULL DEFAULT 0 CHECK (total >= 0),
  tanggal TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Jakarta'),
  catatan TEXT NOT NULL DEFAULT '',
  pengguna_id INTEGER REFERENCES pengguna(id)
);

CREATE TABLE IF NOT EXISTS item_pembelian (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pembelian_id INTEGER NOT NULL REFERENCES pembelian(id) ON DELETE CASCADE,
  bahan_id INTEGER NOT NULL REFERENCES bahan(id),
  jumlah DOUBLE PRECISION NOT NULL CHECK (jumlah > 0),
  harga_satuan INTEGER NOT NULL CHECK (harga_satuan >= 0),
  subtotal INTEGER NOT NULL CHECK (subtotal >= 0)
);

CREATE TABLE IF NOT EXISTS stok_opname (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nomor TEXT NOT NULL UNIQUE,
  tanggal TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Jakarta'),
  catatan TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'selesai' CHECK (status IN ('selesai')),
  pengguna_id INTEGER REFERENCES pengguna(id)
);

CREATE TABLE IF NOT EXISTS item_opname (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  opname_id INTEGER NOT NULL REFERENCES stok_opname(id) ON DELETE CASCADE,
  bahan_id INTEGER NOT NULL REFERENCES bahan(id),
  stok_fisik DOUBLE PRECISION NOT NULL CHECK (stok_fisik >= 0),
  stok_sistem DOUBLE PRECISION NOT NULL,
  selisih DOUBLE PRECISION NOT NULL,
  alasan TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS menu (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama TEXT NOT NULL,
  harga INTEGER NOT NULL CHECK (harga >= 0),
  deskripsi TEXT NOT NULL DEFAULT '',
  kategori TEXT NOT NULL,
  foto TEXT,
  aktif BOOLEAN NOT NULL DEFAULT TRUE,
  dibuat_pada TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Jakarta')
);

CREATE TABLE IF NOT EXISTS resep (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  menu_id INTEGER NOT NULL REFERENCES menu(id) ON DELETE CASCADE,
  bahan_id INTEGER NOT NULL REFERENCES bahan(id) ON DELETE RESTRICT,
  jumlah_per_porsi DOUBLE PRECISION NOT NULL CHECK (jumlah_per_porsi > 0),
  UNIQUE (menu_id, bahan_id)
);

CREATE TABLE IF NOT EXISTS varian (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  menu_id INTEGER NOT NULL REFERENCES menu(id) ON DELETE CASCADE,
  nama TEXT NOT NULL,
  harga_tambahan INTEGER NOT NULL DEFAULT 0 CHECK (harga_tambahan >= 0),
  aktif BOOLEAN NOT NULL DEFAULT TRUE,
  UNIQUE (menu_id, nama)
);

CREATE TABLE IF NOT EXISTS item_varian (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  varian_id INTEGER NOT NULL REFERENCES varian(id) ON DELETE CASCADE,
  bahan_id INTEGER NOT NULL REFERENCES bahan(id),
  jumlah_per_porsi DOUBLE PRECISION NOT NULL CHECK (jumlah_per_porsi > 0),
  UNIQUE (varian_id, bahan_id)
);

CREATE TABLE IF NOT EXISTS slot_waktu (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tanggal DATE NOT NULL,
  jam TEXT NOT NULL,
  kuota INTEGER NOT NULL CHECK (kuota > 0),
  terisi INTEGER NOT NULL DEFAULT 0 CHECK (terisi >= 0),
  UNIQUE (tanggal, jam)
);

CREATE TABLE IF NOT EXISTS preorder (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kode TEXT NOT NULL UNIQUE,
  kode_lacak TEXT NOT NULL UNIQUE,
  nama_pelanggan TEXT NOT NULL,
  whatsapp TEXT NOT NULL,
  waktu_ambil TEXT NOT NULL,
  slot_id INTEGER REFERENCES slot_waktu(id),
  catatan TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'baru' CHECK (status IN ('baru', 'diproses', 'selesai', 'batal')),
  penjualan_id INTEGER,
  dibuat_pada TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Jakarta')
);

CREATE TABLE IF NOT EXISTS item_preorder (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  preorder_id INTEGER NOT NULL REFERENCES preorder(id) ON DELETE CASCADE,
  menu_id INTEGER NOT NULL,
  varian_id INTEGER,
  nama_menu TEXT NOT NULL,
  nama_varian TEXT NOT NULL DEFAULT '',
  harga_satuan INTEGER NOT NULL CHECK (harga_satuan >= 0),
  jumlah INTEGER NOT NULL CHECK (jumlah > 0),
  subtotal INTEGER NOT NULL CHECK (subtotal >= 0),
  hpp INTEGER NOT NULL DEFAULT 0 CHECK (hpp >= 0)
);

CREATE TABLE IF NOT EXISTS penjualan (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nomor TEXT NOT NULL UNIQUE,
  total INTEGER NOT NULL CHECK (total >= 0),
  diskon INTEGER NOT NULL DEFAULT 0 CHECK (diskon >= 0),
  metode TEXT NOT NULL CHECK (metode IN ('tunai', 'qris', 'transfer')),
  catatan TEXT NOT NULL DEFAULT '',
  sumber TEXT NOT NULL DEFAULT 'kasir' CHECK (sumber IN ('kasir', 'preorder')),
  kasir_id INTEGER REFERENCES pengguna(id),
  preorder_id INTEGER,
  dibuat_pada TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Jakarta')
);

CREATE TABLE IF NOT EXISTS item_penjualan (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  penjualan_id INTEGER NOT NULL REFERENCES penjualan(id) ON DELETE CASCADE,
  menu_id INTEGER NOT NULL,
  varian_id INTEGER,
  nama_menu TEXT NOT NULL,
  nama_varian TEXT NOT NULL DEFAULT '',
  harga_satuan INTEGER NOT NULL CHECK (harga_satuan >= 0),
  jumlah INTEGER NOT NULL CHECK (jumlah > 0),
  subtotal INTEGER NOT NULL CHECK (subtotal >= 0),
  hpp INTEGER NOT NULL DEFAULT 0 CHECK (hpp >= 0)
);

CREATE TABLE IF NOT EXISTS kategori_pengeluaran (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama TEXT NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS pengeluaran (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kategori_id INTEGER NOT NULL REFERENCES kategori_pengeluaran(id),
  nama TEXT NOT NULL,
  jumlah INTEGER NOT NULL CHECK (jumlah >= 0),
  tanggal TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Jakarta'),
  catatan TEXT NOT NULL DEFAULT '',
  pengguna_id INTEGER REFERENCES pengguna(id)
);

CREATE TABLE IF NOT EXISTS tutup_kasir (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tanggal DATE NOT NULL UNIQUE,
  kasir_id INTEGER REFERENCES pengguna(id),
  total_tunai INTEGER NOT NULL DEFAULT 0,
  total_qris INTEGER NOT NULL DEFAULT 0,
  total_transfer INTEGER NOT NULL DEFAULT 0,
  kas_fisik INTEGER NOT NULL DEFAULT 0,
  selisih INTEGER NOT NULL DEFAULT 0,
  catatan TEXT NOT NULL DEFAULT '',
  dibuat_pada TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Jakarta')
);

CREATE INDEX IF NOT EXISTS idx_resep_menu ON resep(menu_id);
CREATE INDEX IF NOT EXISTS idx_varian_menu ON varian(menu_id);
CREATE INDEX IF NOT EXISTS idx_penjualan_waktu ON penjualan(dibuat_pada);
CREATE INDEX IF NOT EXISTS idx_item_penjualan ON item_penjualan(penjualan_id);
CREATE INDEX IF NOT EXISTS idx_preorder_status ON preorder(status);
CREATE INDEX IF NOT EXISTS idx_preorder_lacak ON preorder(kode_lacak);
CREATE INDEX IF NOT EXISTS idx_item_preorder ON item_preorder(preorder_id);
CREATE INDEX IF NOT EXISTS idx_pergerakan_bahan ON pergerakan_stok(bahan_id);
CREATE INDEX IF NOT EXISTS idx_pergerakan_waktu ON pergerakan_stok(dibuat_pada);
CREATE INDEX IF NOT EXISTS idx_pengeluaran_tanggal ON pengeluaran(tanggal);
CREATE INDEX IF NOT EXISTS idx_audit_waktu ON log_audit(dibuat_pada);

